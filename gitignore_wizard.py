#!/usr/bin/env python3
"""Generate a .gitignore file from simple built-in presets."""

import argparse
from pathlib import Path

PRESETS = {
    "python": ["__pycache__/", "*.py[cod]", ".venv/", "venv/", "dist/", "build/", "*.egg-info/"],
    "node": ["node_modules/", "npm-debug.log*", "yarn-error.log*", "dist/"],
    "vscode": [".vscode/*", "!.vscode/extensions.json"],
    "os": [".DS_Store", "Thumbs.db", "Desktop.ini"],
}


def generate(names: list[str]) -> str:
    lines = ["# Generated by Gitignore Wizard", ""]
    seen = set(lines)
    for name in names:
        for line in PRESETS[name]:
            if line not in seen:
                lines.append(line)
                seen.add(line)
        lines.append("")
    return "\n".join(lines).rstrip() + "\n"


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("presets", nargs="+", choices=sorted(PRESETS))
    parser.add_argument("--output", type=Path, default=Path(".gitignore"))
    args = parser.parse_args()
    content = generate(args.presets)
    args.output.write_text(content, encoding="utf-8")
    print(f"Wrote {len(content.splitlines())} lines to {args.output}")


if __name__ == "__main__":
    main()
